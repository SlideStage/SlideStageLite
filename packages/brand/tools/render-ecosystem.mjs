#!/usr/bin/env node
// @slidestage/brand · render-ecosystem.mjs
//
// Renders the SlideStage product registry (`src/products.data.mjs`) into a
// repo-specific README marker block, keeping every consumer's "SlideStage
// ecosystem" section in lock-step with the canonical list.
//
// Two run modes:
//   --target=<README>        Rewrite the marker block in <README> in place.
//   --target=<README> --check Verify the marker block already matches the
//                            current registry; exit non-zero if it doesn't.
//
// Optional flags:
//   --lang=en|zh|both        Which summary column to render. Default `en`.
//                            `both` renders English with a Chinese fallback
//                            below — used by Lite's README_cn.md when called
//                            twice with separate marker IDs.
//   --self=<slug>            Hide the row for the current repo's own product
//                            (e.g. the Lite README shouldn't link back to
//                            itself). Slug must match `products.data.mjs`.
//   --marker=<id>            Override the marker block id (default
//                            `slidestage-ecosystem`). Useful when a single
//                            README has multiple blocks (e.g. an en + zh
//                            variant).
//   --quiet                  Suppress success log; only print errors.
//
// The marker block is delimited by these HTML comments:
//
//   <!-- BEGIN: <marker-id> · auto-generated by @slidestage/brand · DO NOT EDIT -->
//   …generated table…
//   <!-- END: <marker-id> -->
//
// Anything between the markers will be replaced on each run. The comments
// themselves are preserved. If the markers are missing, the tool fails and
// asks you to add them manually (so we never accidentally inject content into
// an unintended location).

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { SLIDESTAGE_PRODUCTS_DATA } from '../src/products.data.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const BRAND_PKG_ROOT = dirname(HERE);

// We render `<img>` tags using GitHub raw URLs so the README renders
// correctly on GitHub regardless of which repo it lives in (consumer repos
// don't commit the brand assets locally). When the assets move, update this
// single constant.
const ASSETS_BASE_URL =
  'https://raw.githubusercontent.com/SlideStage/SlideStageLite/main/packages/brand/assets/png';

const DEFAULT_MARKER_ID = 'slidestage-ecosystem';
const MARK_WIDTH = 84;
const TABLE_COLUMNS = 3; // Mirrors the legacy hand-written layout.

function parseArgs(argv) {
  const args = {
    target: null,
    check: false,
    lang: 'en',
    self: null,
    marker: DEFAULT_MARKER_ID,
    quiet: false,
  };
  for (const raw of argv) {
    if (raw === '--check') {
      args.check = true;
    } else if (raw === '--quiet') {
      args.quiet = true;
    } else if (raw.startsWith('--target=')) {
      args.target = raw.slice('--target='.length);
    } else if (raw.startsWith('--lang=')) {
      args.lang = raw.slice('--lang='.length);
    } else if (raw.startsWith('--self=')) {
      args.self = raw.slice('--self='.length);
    } else if (raw.startsWith('--marker=')) {
      args.marker = raw.slice('--marker='.length);
    } else {
      throw new Error(`render-ecosystem: unknown flag "${raw}"`);
    }
  }
  if (!args.target) {
    throw new Error(
      'render-ecosystem: --target=<path-to-README> is required',
    );
  }
  if (args.lang !== 'en' && args.lang !== 'zh' && args.lang !== 'both') {
    throw new Error(
      `render-ecosystem: --lang must be one of en|zh|both (got "${args.lang}")`,
    );
  }
  return args;
}

function escapeHtml(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function summaryToHtml(summary) {
  // The summary field uses Markdown-style inline code (`backticks`). We render
  // those as <code> so the table is uniform across GitHub and rendered docs.
  return escapeHtml(summary).replace(/`([^`]+)`/g, '<code>$1</code>');
}

function renderTable(products, lang) {
  if (products.length === 0) {
    return '_No products registered._';
  }
  const rows = [];
  for (let i = 0; i < products.length; i += TABLE_COLUMNS) {
    const slice = products.slice(i, i + TABLE_COLUMNS);
    // Pad the final row with empty cells so column widths stay consistent.
    while (slice.length < TABLE_COLUMNS) {
      slice.push(null);
    }
    rows.push(renderRowWithPadding(slice, lang));
  }
  return ['<table>', rows.join('\n'), '</table>'].join('\n');
}

function renderRowWithPadding(products, lang) {
  const cells = products.map((p) => {
    if (!p) {
      return `    <td align="center" valign="top" width="33%"></td>`;
    }
    const markUrl = `${ASSETS_BASE_URL}/${p.markPng}`;
    const summary = lang === 'zh' ? p.summaryZh : p.summary;
    const summaryHtml = summaryToHtml(summary);
    const taglineHtml = escapeHtml(p.tagline);
    const nameHtml = escapeHtml(p.name);
    return [
      `    <td align="center" valign="top" width="33%">`,
      `      <a href="${p.repo}"><img src="${markUrl}" width="${MARK_WIDTH}" alt="${nameHtml}"></a><br/>`,
      `      <strong>${nameHtml}</strong><br/>`,
      `      <sub>${taglineHtml}</sub><br/>`,
      `      <sub>${summaryHtml}</sub>`,
      `    </td>`,
    ].join('\n');
  });
  return ['  <tr>', cells.join('\n'), '  </tr>'].join('\n');
}

function renderBlockBody(products, lang) {
  const apps = products.filter((p) => p.kind === 'app');
  const packages = products.filter((p) => p.kind === 'package');
  const parts = [renderTable(apps, lang)];
  if (packages.length > 0) {
    parts.push('');
    parts.push('**Foundation packages** (consumed via npm):');
    parts.push('');
    for (const p of packages) {
      const npmBadge = p.npm
        ? ` · [![npm](https://img.shields.io/npm/v/${p.npm}.svg?style=flat-square&label=npm)](https://www.npmjs.com/package/${p.npm})`
        : '';
      const summary = lang === 'zh' ? p.summaryZh : p.summary;
      parts.push(`- [\`${p.name}\`](${p.repo}) — ${summary}${npmBadge}`);
    }
  }
  return parts.join('\n');
}

function renderMarkerBlock(products, lang, markerId) {
  const begin = `<!-- BEGIN: ${markerId} · auto-generated by @slidestage/brand · DO NOT EDIT -->`;
  const end = `<!-- END: ${markerId} -->`;
  const body = renderBlockBody(products, lang);
  return [begin, body, end].join('\n');
}

function spliceBlock(existing, markerId, replacement) {
  const beginPattern = new RegExp(
    `<!--\\s*BEGIN:\\s*${escapeRegex(markerId)}\\b[^>]*-->`,
    'm',
  );
  const endPattern = new RegExp(`<!--\\s*END:\\s*${escapeRegex(markerId)}\\s*-->`, 'm');
  const beginMatch = beginPattern.exec(existing);
  const endMatch = endPattern.exec(existing);
  if (!beginMatch || !endMatch) {
    throw new Error(
      `render-ecosystem: marker block "${markerId}" not found. ` +
        `Add the following to the target file to anchor the generated section:\n\n` +
        `<!-- BEGIN: ${markerId} · auto-generated by @slidestage/brand · DO NOT EDIT -->\n` +
        `<!-- END: ${markerId} -->\n`,
    );
  }
  if (beginMatch.index > endMatch.index) {
    throw new Error(
      `render-ecosystem: BEGIN/END markers for "${markerId}" are in the wrong order.`,
    );
  }
  const before = existing.slice(0, beginMatch.index);
  const after = existing.slice(endMatch.index + endMatch[0].length);
  return `${before}${replacement}${after}`;
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const targetPath = resolve(process.cwd(), args.target);
  const original = await readFile(targetPath, 'utf8');

  const filteredProducts = args.self
    ? SLIDESTAGE_PRODUCTS_DATA.filter((p) => p.slug !== args.self)
    : SLIDESTAGE_PRODUCTS_DATA;

  const block = renderMarkerBlock(filteredProducts, args.lang, args.marker);
  const updated = spliceBlock(original, args.marker, block);

  if (args.check) {
    if (updated === original) {
      if (!args.quiet) {
        console.log(
          `[render-ecosystem] OK · ${targetPath} marker "${args.marker}" is up-to-date.`,
        );
      }
      return;
    }
    console.error(
      `[render-ecosystem] STALE · ${targetPath} marker "${args.marker}" differs from registry. ` +
        `Run \`pnpm render:ecosystem\` to regenerate.`,
    );
    process.exitCode = 1;
    return;
  }

  if (updated === original) {
    if (!args.quiet) {
      console.log(
        `[render-ecosystem] unchanged · ${targetPath} marker "${args.marker}".`,
      );
    }
    return;
  }
  await writeFile(targetPath, updated, 'utf8');
  if (!args.quiet) {
    console.log(
      `[render-ecosystem] wrote · ${targetPath} marker "${args.marker}".`,
    );
  }
}

// Only run main() when invoked as a CLI (not when imported for tests).
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main().catch((err) => {
    console.error(err.message ?? err);
    process.exit(1);
  });
}

export {
  SLIDESTAGE_PRODUCTS_DATA,
  renderMarkerBlock,
  renderBlockBody,
  spliceBlock,
  ASSETS_BASE_URL,
  BRAND_PKG_ROOT,
};
